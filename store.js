/* Shared data layer for dashboard (index.html) and admin (admin.html).
 * Published data lives in data.js (window.CI_SEED). Unpublished edits made in
 * admin are kept in localStorage as a draft until exported as a new data.js. */
(function () {
  const KEY = "gmi-ci-draft-v1";
  const clone = (o) => JSON.parse(JSON.stringify(o));

  function load() {
    try {
      const raw = localStorage.getItem(KEY);
      if (raw) {
        const d = JSON.parse(raw);
        if (d && Array.isArray(d.items)) return { data: d, isDraft: true };
      }
    } catch (e) { /* fall through to seed */ }
    return { data: clone(window.CI_SEED), isDraft: false };
  }

  function save(data) {
    data.updatedAt = isoDate(new Date());
    localStorage.setItem(KEY, JSON.stringify(data));
  }

  function discardDraft() { localStorage.removeItem(KEY); }

  /* ---- dates (local time, Monday-start weeks) ---- */
  function isoDate(d) {
    const p = (n) => String(n).padStart(2, "0");
    return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
  }
  function parse(s) { const [y, m, d] = s.split("-").map(Number); return new Date(y, m - 1, d); }
  function addDays(d, n) { const x = new Date(d); x.setDate(x.getDate() + n); return x; }
  function weekStart(d) { const x = new Date(d.getFullYear(), d.getMonth(), d.getDate()); const wd = (x.getDay() + 6) % 7; return addDays(x, -wd); }

  function periodRange(key, today) {
    const t = new Date(today.getFullYear(), today.getMonth(), today.getDate());
    const ws = weekStart(t);
    switch (key) {
      case "thisweek": return [ws, addDays(ws, 6), "This week"];
      case "lastweek": return [addDays(ws, -7), addDays(ws, -1), "Last week"];
      case "7d":       return [addDays(t, -6), t, "Last 7 days"];
      case "30d":      return [addDays(t, -29), t, "Last 30 days"];
      case "month":    return [new Date(t.getFullYear(), t.getMonth(), 1), new Date(t.getFullYear(), t.getMonth() + 1, 0), "This month"];
      case "90d":      return [addDays(t, -89), t, "Last 90 days"];
      default:         return [new Date(2000, 0, 1), new Date(2100, 0, 1), "All time"];
    }
  }
  /* The comparison window immediately before [a,b] with the same length */
  function prevRange(a, b) {
    const len = Math.round((b - a) / 864e5) + 1;
    return [addDays(a, -len), addDays(a, -1)];
  }

  function exportDataJs(data) {
    const header = "/* GMI Cloud · Competitive Intel Radar — published dataset.\n * Generated by admin.html on " + isoDate(new Date()) + ". Replace data.js on the server with this file to publish.\n */\n";
    return header + "window.CI_SEED = " + JSON.stringify(data, null, 2) + ";\n";
  }

  function download(name, text, type) {
    const blob = new Blob([text], { type: type || "text/plain" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob); a.download = name; a.click();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  }

  function esc(s) {
    return String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  }

  window.CI = { load, save, discardDraft, isoDate, parse, addDays, weekStart, periodRange, prevRange, exportDataJs, download, esc, KEY };
})();
